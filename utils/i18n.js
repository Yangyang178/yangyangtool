  getLanguage: function() {
    return storageUtil.get(LANG_KEY, 'zh')
  },

  setLanguage: function(lang) {
    storageUtil.set(LANG_KEY, lang)
  },

  getLanguages: function() {
    return [
      { id: 'zh', name: LANGUAGES.zh.name, icon: LANGUAGES.zh.icon },
      { id: 'en', name: LANGUAGES.en.name, icon: LANGUAGES.en.icon }
    ]
  },

  t: function(key, params) {
    var lang = this.getLanguage()
    var dict = LANGUAGES[lang] || LANGUAGES.zh
    var text = dict[key]
    if (text === undefined || text === null) {
      dict = LANGUAGES.zh
      text = dict[key]
    }
    if (text === undefined || text === null) {
      return key
    }
    if (params) {
      for (var k in params) {
        text = text.replace('{' + k + '}', params[k])
      }
    }
    return text
  },

  getAllTexts: function() {
    var lang = this.getLanguage()
    var dict = LANGUAGES[lang] || LANGUAGES.zh
    var result = {}
    for (var key in dict) {
      result[key] = dict[key]
    }
    return result
  },

  getToolName: function(id, defaultName) {
    var lang = this.getLanguage()
    if (lang === 'en') {
      var enName = TOOL_NAMES_EN[id]
      if (enName) return enName
    }
    return defaultName
  },

  getToolDesc: function(id, defaultDesc) {
    var lang = this.getLanguage()
    if (lang === 'en') {
      var enDesc = TOOL_DESCS_EN[id]
      if (enDesc) return enDesc
    }
    return defaultDesc
  },

  getCategoryName: function(categoryId) {
    var lang = this.getLanguage()
    if (lang === 'en') {
      var enName = CATEGORY_NAMES_EN[categoryId]
      if (enName) return enName
    }
    return CATEGORY_NAMES_ZH[categoryId] || categoryId
  },

  getHotSearchWords: function() {
    var lang = this.getLanguage()
    if (lang === 'en') return HOT_SEARCH_EN
    return HOT_SEARCH_ZH
  },

  translateTools: function(toolsList) {
    var lang = this.getLanguage()
    var namesDict = lang === 'en' ? TOOL_NAMES_EN : TOOL_NAMES_ZH
    var descsDict = lang === 'en' ? TOOL_DESCS_EN : TOOL_DESCS_ZH
    var result = []
    for (var i = 0; i < toolsList.length; i++) {
      var t = {}
      for (var key in toolsList[i]) t[key] = toolsList[i][key]
      var translatedName = namesDict[t.id]
      if (translatedName) t.name = translatedName
      var translatedDesc = descsDict[t.id]
      if (translatedDesc) t.description = translatedDesc
      result.push(t)
    }
    return result
  },

  translateCategories: function(categoriesList) {
    var lang = this.getLanguage()
    var namesDict = lang === 'en' ? CATEGORY_NAMES_EN : CATEGORY_NAMES_ZH
    var result = []
    for (var i = 0; i < categoriesList.length; i++) {
      var c = {}
      for (var key in categoriesList[i]) c[key] = categoriesList[i][key]
      var translatedName = namesDict[c.id]
      if (translatedName) c.name = translatedName
      result.push(c)
    }
    return result
  },

  getToolPageTexts: function(toolId) {
    var lang = this.getLanguage()
    var texts = TOOL_PAGE_TEXTS[lang] || TOOL_PAGE_TEXTS['zh']
    return texts[toolId] || {}
  }
